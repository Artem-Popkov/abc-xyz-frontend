// Товары перемешиваем по кругу (первый из каждой категории, потом второй…), чтобы самыми
// продаваемыми не оказались товары одной категории: спрос ниже зависит от порядкового номера.
const ORDERED = []
for (let i = 0; CATALOG.some(([, names]) => i < names.length); i += 1) {
  CATALOG.forEach(([category, names]) => {
    if (i < names.length) ORDERED.push({ category, name: names[i] })
  })
}

// Особые товары: продаются только в указанные месяцы (или не продаются вовсе).
const SPECIAL = [
  { name: 'Ёлочные игрушки (набор)', category: 'Сезонные товары', months: [11, 12], demand: 60, price: 890 },
  { name: 'Кулич пасхальный 500 г', category: 'Сезонные товары', months: [4], demand: 120, price: 420 },
  { name: 'Мангал складной', category: 'Сезонные товары', months: [], demand: 0, price: 2490 },
]

const YEAR = 2025

function seededRandom(seed) {
  let state = seed
  return () => {
    state = (state * 1664525 + 1013904223) % 4294967296
    return state / 4294967296
  }
}

// Раскладывает месячное количество на k чеков (в каждом не меньше 1 шт.).
function splitQuantity(total, k, random) {
  const parts = new Array(k).fill(1)
  for (let rest = total - k; rest > 0; rest -= 1) parts[Math.floor(random() * k)] += 1
  return parts
}

function buildSample() {
  const random = seededRandom(20250101)
  const items = []
  const sales = []
  let docNumber = 0

  const addMonthSales = (code, month, quantity, price) => {
    if (quantity <= 0) return
    const k = Math.min(quantity, 2 + Math.floor(random() * 4))
    splitQuantity(quantity, k, random).forEach((qty) => {
      docNumber += 1
      const day = 1 + Math.floor(random() * 28)
      const date = `${YEAR}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`
      sales.push({ doc_id: `CHK-${String(docNumber).padStart(5, '0')}`, date, item_code: code, qty, price })
    })
  }

  let index = 0
  ORDERED.forEach(({ category, name }) => {
    const code = `P${String(index + 1).padStart(3, '0')}`
    const profile = index % 3
    // Базовый спрос падает с номером товара: получается «длинный хвост» для Парето.
    const base = Math.round(900 / (index + 1) ** 0.9) + 6
    const price = Math.round((40 + random() * 460) * 100) / 100
    items.push({ item_code: code, name, category })
    for (let month = 1; month <= 12; month += 1) {
      let factor
      if (profile === 0) factor = 0.95 + random() * 0.1
      else if (profile === 1) factor = 0.75 + random() * 0.5
      else factor = random() < 0.2 ? 0 : 0.3 + random() * 2.2
      addMonthSales(code, month, Math.round(base * factor), price)
    }
    index += 1
  })

  SPECIAL.forEach((special) => {
    index += 1
    const code = `P${String(index).padStart(3, '0')}`
    items.push({ item_code: code, name: special.name, category: special.category })
    special.months.forEach((month) => addMonthSales(code, month, special.demand, special.price))
  })

  // Порядок строк как в выгрузке из кассы: по дате, затем по номеру чека.
  sales.sort((a, b) => a.date.localeCompare(b.date) || a.doc_id.localeCompare(b.doc_id))
  return { items, sales }
}

const SAMPLE = buildSample()

export const SAMPLE_ITEMS_CSV =
  ['item_code,name,category', ...SAMPLE.items.map((i) => `${i.item_code},"${i.name}",${i.category}`)].join('\n') + '\n'

export const SAMPLE_SALES_CSV =
  ['doc_id,date,item_code,qty,price', ...SAMPLE.sales.map((s) => `${s.doc_id},${s.date},${s.item_code},${s.qty},${s.price.toFixed(2)}`)].join('\n') + '\n'
